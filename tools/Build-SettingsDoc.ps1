#requires -Version 7.0
<#
.SYNOPSIS
Writes docs/settings.md from core/settings.json.

.DESCRIPTION
core/settings.json is the one list of settings. This turns it into the reference page, with the
name each integration uses for every setting, so the page cannot drift from what the integrations
accept. A test fails when docs/settings.md is not what this script produces.

.PARAMETER PassThru
Return the text instead of writing the file (used by the test).
#>
[CmdletBinding()]
param([switch] $PassThru)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$definition = Get-Content -LiteralPath (Join-Path $root 'core/settings.json') -Raw | ConvertFrom-Json

function ConvertTo-CamelCase {
    param([string] $Name)
    $parts = $Name -split '-'
    return $parts[0] + (($parts | Select-Object -Skip 1 | ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }) -join '')
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Settings')
$lines.Add('')
$lines.Add('<!-- Generated by tools/Build-SettingsDoc.ps1 from core/settings.json. Do not edit by hand. -->')
$lines.Add('')
$lines.Add('Every integration accepts the same settings and applies the same defaults. Only the spelling of')
$lines.Add('the name changes with the platform''s convention. The step prints the effective value of every')
$lines.Add('setting at the start of each run (secrets are shown only as set or not set).')
$lines.Add('')
$lines.Add('## Names on each platform')
$lines.Add('')
$lines.Add('| Setting | GitHub Actions, CircleCI | Azure DevOps, Jenkins | GitLab | Environment variable |')
$lines.Add('| --- | --- | --- | --- | --- |')
foreach ($item in $definition.settings) {
    $camel = ConvertTo-CamelCase $item.name
    $snake = $item.name -replace '-', '_'
    if ($item.secret) {
        $lines.Add(('| {0} (secret) | `{0}` (GitHub), `{0}-variable` (CircleCI) | `{1}` (Azure DevOps), `{1}CredentialsId` (Jenkins) | CI/CD variable `{2}` | `{2}` |' -f $item.name, $camel, $item.env))
    }
    else {
        $lines.Add(('| {0} | `{0}` | `{1}` | `{2}` | `{3}` |' -f $item.name, $camel, $snake, $item.env))
    }
}
$lines.Add('')
$lines.Add('Secrets are never plain settings. Each platform takes them from its own secret store: a GitHub')
$lines.Add('secret, a secret pipeline variable in Azure DevOps, a masked CI/CD variable in GitLab, a context')
$lines.Add('variable in CircleCI, and a credentials ID in Jenkins.')

foreach ($group in ($definition.settings.group | Select-Object -Unique)) {
    $lines.Add('')
    $lines.Add("## $group")
    $lines.Add('')
    $lines.Add('| Setting | Default | Allowed values | Description |')
    $lines.Add('| --- | --- | --- | --- |')
    foreach ($item in ($definition.settings | Where-Object group -EQ $group)) {
        $default = if ($item.default) { '`{0}`' -f $item.default } else { '(empty)' }
        $values = if ($item.PSObject.Properties['values']) { ($item.values | ForEach-Object { '`{0}`' -f $_ }) -join ', ' } else { 'any' }
        $name = if ($item.secret) { '`{0}` (secret)' -f $item.name } else { '`{0}`' -f $item.name }
        $lines.Add(('| {0} | {1} | {2} | {3} |' -f $name, $default, $values, $item.description))
    }
}

$lines.Add('')
$lines.Add('## Outputs')
$lines.Add('')
$lines.Add('| Output | Description |')
$lines.Add('| --- | --- |')
foreach ($item in $definition.outputs) { $lines.Add(('| `{0}` | {1} |' -f $item.name, $item.description)) }
$lines.Add('')
$lines.Add('How to read an output on each platform:')
$lines.Add('')
$lines.Add('| Platform | How |')
$lines.Add('| --- | --- |')
$lines.Add('| GitHub Actions | `${{ steps.<id>.outputs.status }}` |')
$lines.Add('| Azure DevOps | `$(<stepName>.status)`; hyphens become underscores, for example `$(<stepName>.fail_count)` |')
$lines.Add('| GitLab | Later jobs receive `DSCPR_STATUS`, `DSCPR_FAIL_COUNT` and so on as variables (dotenv report) |')
$lines.Add('| CircleCI | Read `<report-path>/outputs.env` in a later step |')
$lines.Add('| Jenkins | The step returns a map: `result.status`, `result.failCount` and so on |')
$lines.Add('| Anything else | `<report-path>/outputs.env` (`DSCPR_STATUS=...`) and `<report-path>/result.json` |')
$lines.Add('')
$lines.Add('The step also exits with a code: `0` success, `1` the run failed (or could not run), `2` the')
$lines.Add('settings are not valid.')

$text = ($lines -join "`n") + "`n"
if ($PassThru) { return $text }
Set-Content -LiteralPath (Join-Path $root 'docs/settings.md') -Value $text -NoNewline -Encoding utf8
Write-Host 'Wrote docs/settings.md'
