'use strict';
// Turns the cases in ../cases into one Azure Pipelines YAML file, and reads a finished run back
// into pass or fail per case. No network here: run-live.js does the talking, and pipeline.test.js
// tests this file on its own.

const TASK_NAME = 'DscPipelineRunnerIntegrationTest';
// Where the repository pushed to Azure Repos keeps this repository's fixtures.
const FIXTURES = '$(Build.SourcesDirectory)/_fixtures';
const SOURCES = '$(Build.SourcesDirectory)';

const quote = (text) => JSON.stringify(String(text));
const number = (index) => String(index + 1).padStart(2, '0');

function substitute(value) {
  return String(value)
    .replaceAll('{repo}', FIXTURES)
    .replaceAll('{workspace}', SOURCES)
    .replaceAll('{pathsep}', ':')
    .replace(/\{env:[A-Za-z0-9_]+\}/g, '');
}

// A PowerShell single-quoted string.
const single = (text) => `'${String(text).replaceAll("'", "''")}'`;

function mapping(indent, entries) {
  return Object.entries(entries).map(([name, value]) => `${indent}${quote(name)}: ${quote(value)}`);
}

// The pipeline variables every case needs, in one map. Two cases may not give one name two values.
function collectVariables(cases, key) {
  const all = {};
  for (const { name, definition } of cases) {
    for (const [variable, value] of Object.entries(definition[key] || {})) {
      if (variable in all && all[variable] !== value) throw new Error(`Case ${name} gives '${variable}' a different value than an earlier case.`);
      all[variable] = value;
    }
  }
  return all;
}

/**
 * The YAML of the test pipeline: for each case a step that resets the sources directory, the task
 * step, and a step that prints what the checks need (output variables, the recorded call, files).
 * Every step runs whatever happened before it, so one failing case does not hide the others.
 */
function buildPipelineYaml(cases, { pool, vmImage = 'ubuntu-latest', taskMajor = 0 } = {}) {
  const lines = ['# Generated by tests/integration/azure-devops/live/run-live.js. Do not edit.', 'trigger: none', 'pool:'];
  lines.push(pool ? `  name: ${quote(pool)}` : `  vmImage: ${quote(vmImage)}`);

  const variables = collectVariables(cases, 'variables');
  if (Object.keys(variables).length > 0) lines.push('variables:', ...mapping('  ', variables));

  lines.push('steps:', '- checkout: self');
  cases.forEach(({ definition }, index) => {
    const id = number(index);
    const expect = definition.expect || {};

    const prepare = [
      `$s = ${single(SOURCES)}`,
      "Get-ChildItem -LiteralPath $s -Force | Where-Object { $_.Name -notin '.git', '_fixtures' } | Remove-Item -Recurse -Force",
      ...Object.entries(definition.workspace || {}).map(([target, source]) =>
        `Copy-Item -Recurse -LiteralPath (Join-Path $s ${single(`_fixtures/${source}`)}) -Destination (Join-Path $s ${single(target)})`),
      `$null = New-Item -ItemType Directory -Force -Path ${single('$(Agent.TempDirectory)/dscpr-empty-path')}`,
    ];
    lines.push('- pwsh: |', ...prepare.map((line) => `    ${line}`), `  displayName: ${quote(`prepare ${id}`)}`, '  condition: always()');

    const environment = { ...Object.fromEntries(Object.entries(definition.environment || {}).map(([name, value]) => [name, substitute(value)])) };
    environment.DSCPR_TEST_CALL_FILE = `${SOURCES}/call.json`;
    if (definition.hidePowerShell) environment.PATH = '$(Agent.TempDirectory)/dscpr-empty-path';
    lines.push(`- task: ${TASK_NAME}@${taskMajor}`, `  name: case${id}`, `  displayName: ${quote(`case ${id}`)}`, '  condition: always()');
    const inputs = Object.fromEntries(Object.entries(definition.inputs || {}).map(([name, value]) => [name, substitute(value)]));
    if (Object.keys(inputs).length > 0) lines.push('  inputs:', ...mapping('    ', inputs));
    lines.push('  env:', ...mapping('    ', environment));

    const verify = [
      `$s = ${single(SOURCES)}`,
      // Single quotes: the agent replaces the macro before PowerShell sees the line. When the
      // variable was never set, the macro stays as written, which is how the check knows.
      ...Object.keys(expect.outputs || {}).map((output) => `Write-Host ${single(`DSCPR-OUTPUT ${output}=[$(case${id}.${output})]`)}`),
      "$call = Join-Path $s 'call.json'",
      "if (Test-Path -LiteralPath $call) { Write-Host ('DSCPR-CALL ' + (Get-Content -Raw -LiteralPath $call | ConvertFrom-Json -AsHashtable | ConvertTo-Json -Depth 6 -Compress)) } else { Write-Host 'DSCPR-NOCALL' }",
      ...(expect.files || []).map((file) => `Write-Host (${single(`DSCPR-FILE ${file} `)} + (Test-Path -LiteralPath (Join-Path $s ${single(file)})))`),
    ];
    lines.push('- pwsh: |', ...verify.map((line) => `    ${line}`), `  displayName: ${quote(`verify ${id}`)}`, '  condition: always()');
  });
  return `${lines.join('\n')}\n`;
}

// ---- Reading a run back ------------------------------------------------------------------------

const RESULTS = { succeeded: 'Succeeded', failed: 'Failed', succeededwithissues: 'SucceededWithIssues', skipped: 'Skipped', canceled: 'Canceled' };

// The text of each log line, without the timestamp the service puts in front.
function logLines(log) {
  return String(log || '').split(/\r?\n/).map((line) => line.replace(/^\d{4}-\d\d-\d\dT[\d:.]+Z /, ''));
}

function lookup(object, dotted) {
  return dotted.split('.').reduce((value, key) => (value === undefined || value === null ? undefined : value[key]), object);
}

/**
 * Checks one case against the run.
 *   records   the timeline records of the run
 *   logs      (record) => the log text of that record
 * Returns the list of failed checks; empty means the case passed.
 */
function evaluateCase(definition, index, records, logs) {
  const id = number(index);
  const expect = definition.expect || {};
  const failures = [];
  const find = (name) => records.find((record) => record.type === 'Task' && record.name === name);

  const task = find(`case ${id}`);
  if (!task) return [`the run has no step 'case ${id}'`];
  const result = RESULTS[String(task.result || '').toLowerCase()] || String(task.result);
  if (expect.result && result !== expect.result) failures.push(`result is ${result}, expected ${expect.result}`);

  for (const issue of expect.issues || []) {
    const found = (task.issues || []).some((logged) => String(logged.type).toLowerCase() === issue.type && new RegExp(issue.matches).test(logged.message || ''));
    if (!found) failures.push(`no ${issue.type} issue matching /${issue.matches}/ was logged`);
  }

  const taskLog = logLines(logs(task)).join('\n');
  for (const pattern of expect.contains || []) {
    if (!new RegExp(pattern).test(taskLog)) failures.push(`the log does not match /${pattern}/`);
  }
  for (const pattern of expect.notContains || []) {
    if (new RegExp(pattern).test(taskLog)) failures.push(`the log matches /${pattern}/, which it must not`);
  }
  // The service replaces a secret it finds in the log with ***. The task never prints a secret,
  // so the mask must never have been needed.
  if (Object.keys(definition.secretVariables || {}).length > 0 && taskLog.includes('***')) {
    failures.push('the log holds ***: a secret was written to it and masked by the service');
  }

  const verify = find(`verify ${id}`);
  if (!verify) return [...failures, `the run has no step 'verify ${id}'`];
  const lines = logLines(logs(verify));

  for (const [name, wanted] of Object.entries(expect.outputs || {})) {
    const line = lines.filter((text) => text.startsWith(`DSCPR-OUTPUT ${name}=[`)).pop();
    const actual = line ? line.slice(`DSCPR-OUTPUT ${name}=[`.length, -1) : undefined;
    if (actual === undefined || actual === `$(case${id}.${name})`) failures.push(`output variable '${name}' was not set`);
    else if (wanted !== null && typeof wanted === 'object') {
      if (!new RegExp(wanted.matches).test(actual)) failures.push(`output '${name}' is '${actual}', expected to match /${wanted.matches}/`);
    } else if (actual !== String(wanted)) failures.push(`output '${name}' is '${actual}', expected '${wanted}'`);
  }

  const callLine = lines.filter((text) => text.startsWith('DSCPR-CALL ')).pop();
  const called = callLine !== undefined;
  if (!called && !lines.includes('DSCPR-NOCALL')) failures.push('the verify step did not report whether the module was called');
  if (expect.notCalled && called) failures.push('Dsc.PipelineRunner was called, and must not have been');
  if (expect.call) {
    if (!called) failures.push('Dsc.PipelineRunner was not called');
    else {
      let call;
      try { call = JSON.parse(callLine.slice('DSCPR-CALL '.length)); } catch { call = undefined; }
      if (call === undefined) failures.push('the recorded call could not be read from the log');
      else {
        for (const [key, wanted] of Object.entries(expect.call)) {
          const actual = lookup(call, key);
          if (wanted !== null && typeof wanted === 'object' && wanted.matches) {
            if (!new RegExp(wanted.matches).test(String(actual))) failures.push(`the module was called with ${key} = ${JSON.stringify(actual)}, expected to match /${wanted.matches}/`);
          } else if (JSON.stringify(actual) !== JSON.stringify(wanted)) {
            failures.push(`the module was called with ${key} = ${JSON.stringify(actual)}, expected ${JSON.stringify(wanted)}`);
          }
        }
      }
    }
  }

  for (const file of expect.files || []) {
    if (!lines.includes(`DSCPR-FILE ${file} True`)) failures.push(`${file} does not exist in the sources directory`);
  }
  return failures;
}

module.exports = { TASK_NAME, buildPipelineYaml, collectVariables, evaluateCase, logLines };
