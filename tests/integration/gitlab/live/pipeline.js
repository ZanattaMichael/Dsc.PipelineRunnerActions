'use strict';
// Turns the cases in ../cases into the .gitlab-ci.yml of the test project, and reads a finished
// pipeline back into pass or fail per case. No network here: run-live.js does the talking, and
// pipeline.test.js tests this file on its own.

const YAML = require('yaml');

const VERIFY_IMAGE = 'alpine:3.20';
const number = (index) => String(index + 1).padStart(2, '0');

function substitute(value) {
  return String(value)
    .replaceAll('{repo}', '$CI_PROJECT_DIR')
    .replaceAll('{project}', '$CI_PROJECT_DIR')
    .replaceAll('{pathsep}', ':');
}

function substituteDeep(node) {
  if (typeof node === 'string') return substitute(node);
  if (Array.isArray(node)) return node.map(substituteDeep);
  if (node && typeof node === 'object') return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, substituteDeep(value)]));
  return node;
}

// A case that GitLab refuses at pipeline creation cannot share a pipeline with the others.
function isRefused(definition) {
  return Boolean(definition.expect && definition.expect.inputProblems);
}

function reportPath(definition) {
  return (definition.inputs && definition.inputs.report_path) || 'dsc-reports';
}

// The include and the two jobs (the case, and a verify job that prints what the checks need) for
// one case. `component` is the component reference, for example
// gitlab.example.test/root/project/dsc-pipeline-runner@<sha>.
function caseEntries(definition, index, component) {
  const id = number(index);
  const jobName = `case-${id}`;
  const include = { component, inputs: { ...substituteDeep(definition.inputs || {}), job_name: jobName } };
  if (definition.hidePowerShell && !include.inputs.image) include.inputs.image = VERIFY_IMAGE;

  const job = substituteDeep(definition.job || {});
  job.variables = {
    // The step script is fetched from this very commit, through the server's raw file URL.
    DSCPR_CORE_URL: '$CI_SERVER_URL/$CI_PROJECT_PATH/-/raw/$CI_COMMIT_SHA/core/',
    // The stand-in module records its call inside the report directory, so it is an artifact.
    DSCPR_TEST_CALL_FILE: `$CI_PROJECT_DIR/${reportPath(definition)}/call.json`,
    ...(job.variables || {}),
  };
  // Workspace folders come from the pushed repository: copy them in before the component's script.
  const copies = Object.entries(definition.workspace || {}).map(([target, source]) => `cp -r ${substitute(source).replace('$CI_PROJECT_DIR', '.')} ${target}`);
  if (copies.length > 0) job.before_script = copies;

  const expect = definition.expect || {};
  const report = reportPath(definition);
  const verify = {
    stage: 'verify',
    image: VERIFY_IMAGE,
    needs: [{ job: jobName, artifacts: true }],
    when: 'always',
    variables: { GIT_STRATEGY: 'none' },
    script: [
      ...Object.keys(expect.dotenv || {}).map((name) => `echo "DSCPR-OUTPUT ${name}=[$${name}]"`),
      `if [ -f ${report}/call.json ]; then echo "DSCPR-CALL $(tr -d '\\n' < ${report}/call.json)"; else echo DSCPR-NOCALL; fi`,
      ...(expect.artifacts || []).map((artifact) => `if [ -e "${artifact}" ]; then echo "DSCPR-FILE ${artifact} True"; else echo "DSCPR-FILE ${artifact} False"; fi`),
    ],
  };
  return { include, jobs: { [jobName]: job, [`verify-${id}`]: verify } };
}

/**
 * The .gitlab-ci.yml that runs every case GitLab accepts, each as its own job with a verify job
 * after it. `component` is the component reference without the version; `version` is appended.
 */
function buildPipeline(cases, component, version = '$CI_COMMIT_SHA') {
  const pipeline = { stages: ['test', 'verify'], include: [] };
  cases.forEach(({ definition }, index) => {
    if (isRefused(definition)) return;
    const entries = caseEntries(definition, index, `${component}@${version}`);
    pipeline.include.push(entries.include);
    Object.assign(pipeline, entries.jobs);
  });
  return `# Generated by tests/integration/gitlab/live/run-live.js. Do not edit.\n${YAML.stringify(pipeline, { lineWidth: 0 })}`;
}

// A pipeline holding one case that GitLab must refuse, for the lint API.
function buildRefusedPipeline(definition, index, component, version = '$CI_COMMIT_SHA') {
  const entries = caseEntries(definition, index, `${component}@${version}`);
  return YAML.stringify({ stages: ['test', 'verify'], include: [entries.include], ...entries.jobs }, { lineWidth: 0 });
}

// ---- Reading a pipeline back ----------------------------------------------------------------

// A job trace without the colour codes and section markers the runner puts in it.
function cleanTrace(trace) {
  return String(trace || '')
    .replace(/\x1b\[[0-9;]*[A-Za-z]/g, '')
    .replace(/section_(start|end):\d+:[A-Za-z0-9_]+\r?/g, '')
    // GitLab 17+ prefixes every trace line with a timestamp, a stream number and O or E, as in
    // '2026-11-18T02:24:46.049679Z 01O ' (a + after the letter marks a section header).
    .replace(/^\d{4}-\d{2}-\d{2}T[\d:.]+Z \d{2}[OE][+ ]?/gm, '')
    .replace(/\r/g, '');
}

function lookup(object, dotted) {
  return dotted.split('.').reduce((value, key) => (value === undefined || value === null ? undefined : value[key]), object);
}

function matchValue(actual, wanted) {
  if (wanted !== null && typeof wanted === 'object' && wanted.matches) return new RegExp(wanted.matches).test(String(actual));
  return JSON.stringify(actual) === JSON.stringify(wanted);
}

function describeWanted(wanted) {
  return wanted !== null && typeof wanted === 'object' && wanted.matches ? `to match /${wanted.matches}/` : JSON.stringify(wanted);
}

/**
 * Checks one accepted case against the pipeline.
 *   jobs    the pipeline's jobs, as the API lists them (name, status)
 *   traces  (job) => the job's trace
 * Returns the failed checks; empty means the case passed.
 */
function evaluateCase(definition, index, jobs, traces) {
  const id = number(index);
  const expect = definition.expect || {};
  const failures = [];
  const job = jobs.find((candidate) => candidate.name === `case-${id}`);
  if (!job) return [`the pipeline has no job 'case-${id}'`];
  if (expect.status && job.status !== expect.status) failures.push(`status is ${job.status}, expected ${expect.status}`);

  const trace = cleanTrace(traces(job));
  for (const pattern of expect.contains || []) if (!new RegExp(pattern).test(trace)) failures.push(`the log does not match /${pattern}/`);
  for (const pattern of expect.notContains || []) if (new RegExp(pattern).test(trace)) failures.push(`the log matches /${pattern}/, which it must not`);
  // GitLab replaces a masked variable it finds in the log with [MASKED]. The step never prints a
  // secret, so the mask must never have been needed.
  if (Object.keys(definition.maskedVariables || {}).length > 0 && trace.includes('[MASKED]')) failures.push('the log holds [MASKED]: a secret was written to it and masked by GitLab');
  if (expect.exitCode !== undefined) {
    const match = /ERROR: Job failed: (?:exit code|command terminated with exit code) (\d+)/.exec(trace);
    const exitCode = match ? Number(match[1]) : (job.status === 'success' ? 0 : undefined);
    if (exitCode !== expect.exitCode) failures.push(`exit code is ${exitCode === undefined ? 'unknown' : exitCode}, expected ${expect.exitCode}`);
  }

  const verify = jobs.find((candidate) => candidate.name === `verify-${id}`);
  if (!verify) return [...failures, `the pipeline has no job 'verify-${id}'`];
  const lines = cleanTrace(traces(verify)).split('\n').map((line) => line.replace(/^\$ .*$/, ''));
  for (const [name, wanted] of Object.entries(expect.dotenv || {})) {
    const line = lines.filter((text) => text.startsWith(`DSCPR-OUTPUT ${name}=[`)).pop();
    const actual = line ? line.slice(`DSCPR-OUTPUT ${name}=[`.length, -1) : undefined;
    if (actual === undefined || actual === '') failures.push(`the dotenv report does not set ${name}`);
    else if (!matchValue(actual, wanted)) failures.push(`dotenv ${name} is '${actual}', expected ${describeWanted(wanted)}`);
  }
  const callLine = lines.filter((text) => text.startsWith('DSCPR-CALL ')).pop();
  const called = callLine !== undefined;
  if (!called && !lines.includes('DSCPR-NOCALL')) failures.push('the verify job did not report whether the module was called');
  if (expect.notCalled && called) failures.push('Dsc.PipelineRunner was called, and must not have been');
  if (expect.call) {
    if (!called) failures.push('Dsc.PipelineRunner was not called');
    else {
      let call;
      try { call = JSON.parse(callLine.slice('DSCPR-CALL '.length)); } catch { call = undefined; }
      if (call === undefined) failures.push('the recorded call could not be read from the log');
      else {
        for (const [key, wanted] of Object.entries(expect.call)) {
          if (!matchValue(lookup(call, key), wanted)) failures.push(`the module was called with ${key} = ${JSON.stringify(lookup(call, key))}, expected ${describeWanted(wanted)}`);
        }
      }
    }
  }
  for (const artifact of expect.artifacts || []) {
    if (!lines.includes(`DSCPR-FILE ${artifact} True`)) failures.push(`'${artifact}' was not passed on as an artifact`);
  }
  return failures;
}

// Checks one refused case against the lint result ({ valid, errors }).
function evaluateRefusedCase(definition, lint) {
  const expect = definition.expect || {};
  if (lint.valid) return ['GitLab accepted the pipeline, and must not have'];
  const errors = (lint.errors || []).join('\n');
  const failures = [];
  for (const pattern of expect.liveInputProblems || []) if (!new RegExp(pattern).test(errors)) failures.push(`the errors do not match /${pattern}/: ${errors}`);
  return failures;
}

module.exports = { VERIFY_IMAGE, isRefused, caseEntries, buildPipeline, buildRefusedPipeline, cleanTrace, evaluateCase, evaluateRefusedCase };
