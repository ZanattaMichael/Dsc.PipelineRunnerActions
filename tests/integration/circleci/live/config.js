'use strict';
// Turns the cases in ../cases into CircleCI configurations for the CLI's local execute, and reads
// a finished job's output back into pass or fail. No Docker or network here: run-local-execute.js
// does the running, and config.test.js tests this file on its own.

const YAML = require('yaml');

const ORB = 'dsc-pipeline-runner';
const WORKING_DIRECTORY = '/root/project';

function substitute(value) {
  return String(value)
    .replaceAll('{repo}', WORKING_DIRECTORY)
    .replaceAll('{workdir}', WORKING_DIRECTORY)
    .replaceAll('{pathsep}', ':');
}

function substituteDeep(node) {
  if (typeof node === 'string') return substitute(node);
  if (Array.isArray(node)) return node.map(substituteDeep);
  if (node && typeof node === 'object') return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, substituteDeep(value)]));
  return node;
}

// A case that CircleCI refuses when it processes the configuration cannot be run.
function isRefused(definition) {
  return Boolean(definition.expect && definition.expect.parameterProblems);
}

const jobName = (index) => `case-${String(index + 1).padStart(2, '0')}`;

// The job for one case: check out, copy the workspace in, run the orb command with the case's
// parameters (actions-ref pinned to the commit under test), then print what the checks need.
function caseJob(definition, actionsRef) {
  const expect = definition.expect || {};
  const parameters = { ...substituteDeep(definition.parameters || {}), 'actions-ref': actionsRef };
  const report = parameters['report-path'] || 'dsc-reports';
  const steps = ['checkout'];
  for (const [target, source] of Object.entries(definition.workspace || {})) steps.push({ run: `cp -r ${source} ${target}` });
  if (definition.hidePowerShell) {
    // An executor without PowerShell: hide pwsh from every later step.
    steps.push({ run: { name: 'Hide pwsh', command: 'mkdir -p /tmp/no-pwsh && echo "export PATH=/tmp/no-pwsh" >> "$BASH_ENV"' } });
  }
  steps.push({ [`${ORB}/execute`]: parameters });
  steps.push({
    run: {
      name: 'verify',
      when: 'always',
      command: [
        `if [ -f ${report}/outputs.env ]; then while IFS= read -r line; do echo "DSCPR-OUTPUT $line"; done < ${report}/outputs.env; else echo DSCPR-NO-OUTPUTS; fi`,
        'if [ -f call.json ]; then echo "DSCPR-CALL $(tr -d \'\\n\' < call.json)"; else echo DSCPR-NOCALL; fi',
        ...(expect.artifacts || []).map((artifact) => `if [ -e "${artifact}" ]; then echo "DSCPR-FILE ${artifact} True"; else echo "DSCPR-FILE ${artifact} False"; fi`),
      ].join('\n'),
    },
  });
  const job = {
    executor: `${ORB}/default`,
    working_directory: WORKING_DIRECTORY,
    environment: { ...substituteDeep(definition.environment || {}), DSCPR_TEST_CALL_FILE: `${WORKING_DIRECTORY}/call.json` },
    steps,
  };
  return job;
}

/**
 * One configuration holding every case as a job, with the orb inlined from this working tree.
 *   orb         the parsed orb (circleci/orb.yml)
 *   cases       [{ name, definition }]
 *   actionsRef  the commit the step script is fetched from
 */
function buildConfig(orb, cases, actionsRef) {
  const jobs = {};
  cases.forEach(({ definition }, index) => { if (!isRefused(definition)) jobs[jobName(index)] = caseJob(definition, actionsRef); });
  const config = {
    version: 2.1,
    orbs: { [ORB]: inlineOrb(orb) },
    jobs,
    workflows: { 'integration-tests': { jobs: Object.keys(jobs) } },
  };
  return `# Generated by tests/integration/circleci/live/run-local-execute.js. Do not edit.\n${YAML.stringify(config, { lineWidth: 0 })}`;
}

// A configuration holding one case that CircleCI must refuse, for `config validate`.
function buildRefusedConfig(orb, definition, index, actionsRef) {
  const config = {
    version: 2.1,
    orbs: { [ORB]: inlineOrb(orb) },
    jobs: { [jobName(index)]: caseJob(definition, actionsRef) },
    workflows: { 'integration-tests': { jobs: [jobName(index)] } },
  };
  return YAML.stringify(config, { lineWidth: 0 });
}

// An inline orb may not carry the top-level keys of a published orb's metadata.
function inlineOrb(orb) {
  const copy = { ...orb };
  delete copy.version;
  delete copy.display;
  delete copy.examples;
  return copy;
}

// ---- Reading a job back -----------------------------------------------------------------------

function lookup(object, dotted) {
  return dotted.split('.').reduce((value, key) => (value === undefined || value === null ? undefined : value[key]), object);
}

function matchValue(actual, wanted) {
  if (wanted !== null && typeof wanted === 'object' && wanted.matches) return new RegExp(wanted.matches).test(String(actual));
  return JSON.stringify(actual) === JSON.stringify(wanted);
}

function describeWanted(wanted) {
  return wanted !== null && typeof wanted === 'object' && wanted.matches ? `to match /${wanted.matches}/` : JSON.stringify(wanted);
}

// Checks one accepted case against the output of `circleci local execute` and its exit code.
function evaluateCase(definition, output, exitCode) {
  const expect = definition.expect || {};
  const failures = [];
  const text = String(output || '').replace(/\x1b\[[0-9;]*[A-Za-z]/g, '');
  const status = exitCode === 0 ? 'success' : 'failed';
  if (expect.status && status !== expect.status) failures.push(`the job ${status === 'success' ? 'succeeded' : 'failed'} (local execute exited ${exitCode}), expected ${expect.status}`);
  if (expect.exitCode !== undefined && expect.exitCode !== 0) {
    if (!new RegExp(`(Exited with code exit status|exit code) ${expect.exitCode}\\b`).test(text)) failures.push(`the run step did not exit with ${expect.exitCode}`);
  }
  for (const pattern of expect.contains || []) if (!new RegExp(pattern).test(text)) failures.push(`the log does not match /${pattern}/`);
  for (const pattern of expect.notContains || []) if (new RegExp(pattern).test(text)) failures.push(`the log matches /${pattern}/, which it must not`);

  const lines = text.split('\n').map((line) => line.trim());
  for (const [name, wanted] of Object.entries(expect.outputs || {})) {
    const line = lines.filter((candidate) => candidate.startsWith(`DSCPR-OUTPUT ${name}=`)).pop();
    if (!line) failures.push(`outputs.env does not set ${name}${lines.includes('DSCPR-NO-OUTPUTS') ? ' (there is no outputs.env)' : ''}`);
    else if (!matchValue(line.slice(`DSCPR-OUTPUT ${name}=`.length), wanted)) failures.push(`output ${name} is '${line.slice(`DSCPR-OUTPUT ${name}=`.length)}', expected ${describeWanted(wanted)}`);
  }
  const callLine = lines.filter((candidate) => candidate.startsWith('DSCPR-CALL ')).pop();
  const called = callLine !== undefined;
  if (!called && !lines.includes('DSCPR-NOCALL')) failures.push('the verify step did not report whether the module was called');
  if (expect.notCalled && called) failures.push('Dsc.PipelineRunner was called, and must not have been');
  if (expect.call) {
    if (!called) failures.push('Dsc.PipelineRunner was not called');
    else {
      let call;
      try { call = JSON.parse(callLine.slice('DSCPR-CALL '.length)); } catch { call = undefined; }
      if (call === undefined) failures.push('the recorded call could not be read from the log');
      else {
        for (const [key, wanted] of Object.entries(expect.call)) {
          if (!matchValue(lookup(call, key), wanted)) failures.push(`the module was called with ${key} = ${JSON.stringify(lookup(call, key))}, expected ${describeWanted(wanted)}`);
        }
      }
    }
  }
  for (const artifact of expect.artifacts || []) {
    if (!lines.includes(`DSCPR-FILE ${artifact} True`)) failures.push(`'${artifact}' does not exist for store_artifacts`);
  }
  return failures;
}

// Checks one refused case against the output of `circleci config validate` and its exit code.
function evaluateRefusedCase(definition, output, exitCode) {
  const expect = definition.expect || {};
  if (exitCode === 0) return ['CircleCI accepted the configuration, and must not have'];
  const text = String(output || '');
  const failures = [];
  for (const pattern of expect.liveParameterProblems || []) if (!new RegExp(pattern).test(text)) failures.push(`the errors do not match /${pattern}/: ${text.slice(0, 500)}`);
  return failures;
}

module.exports = { ORB, WORKING_DIRECTORY, isRefused, jobName, caseJob, buildConfig, buildRefusedConfig, inlineOrb, evaluateCase, evaluateRefusedCase };
